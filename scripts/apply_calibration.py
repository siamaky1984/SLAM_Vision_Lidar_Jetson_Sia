"""Apply ONE camera calibration to every consumer so intrinsics cannot drift apart.

Input: the ost.yaml written by `ros2 run camera_calibration cameracalibrator`
       (pinhole / plumb_bob model).

Outputs:
  ros2_ws/src/camera_launch/config/camera_info.yaml          v4l2_camera camera_info (RTAB-Map)
  ros2_ws/src/orb_slam3_wrapper/config/orb_slam3.yaml        `camera:` block updated in place
  ros2_ws/src/orb_slam3_wrapper/config/orb_slam3_settings.yaml  ORB-SLAM3 native settings file

Usage:
  python3 scripts/apply_calibration.py ~/.ros/camera_info/ost.yaml [--fps 15]
Then rebuild (colcon build) so the files are installed.
"""

import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'ros2_ws' / 'src'


def load(path):
    d = yaml.safe_load(Path(path).read_text())
    model = d.get('distortion_model', 'plumb_bob')
    if model not in ('plumb_bob', 'rational_polynomial'):
        sys.exit(f'Unsupported distortion_model: {model}')
    K = d['camera_matrix']['data']
    dist = list(d['distortion_coefficients']['data']) + [0.0] * 5
    if K[0] <= 0 or K[4] <= 0:
        sys.exit('Calibration has non-positive focal length; refusing to apply.')
    return d, dict(fx=K[0], fy=K[4], cx=K[2], cy=K[5],
                   k1=dist[0], k2=dist[1], p1=dist[2], p2=dist[3], k3=dist[4],
                   width=int(d['image_width']), height=int(d['image_height']))


def write_camera_info(d):
    d = dict(d)
    d['camera_name'] = 'camera'
    out = SRC / 'camera_launch' / 'config' / 'camera_info.yaml'
    out.write_text(yaml.safe_dump(d, default_flow_style=None))
    print(f'wrote {out}')


def update_orb_params(c, fps):
    path = SRC / 'orb_slam3_wrapper' / 'config' / 'orb_slam3.yaml'
    text = path.read_text()
    for key, val in dict(c, fps=fps).items():
        # only touch the indented keys inside the `camera:` block
        text, n = re.subn(rf'(?m)^(      {key}:\s*)[-\d.eE+]+', rf'\g<1>{val}', text)
        if n != 1:
            sys.exit(f'Could not update camera.{key} in {path}')
    path.write_text(text)
    print(f'updated {path}')


def write_orb_settings(c, fps):
    out = SRC / 'orb_slam3_wrapper' / 'config' / 'orb_slam3_settings.yaml'
    out.write_text(f'''%YAML:1.0
# Generated by scripts/apply_calibration.py – do not edit by hand.
File.version: "1.0"
Camera.type: "PinHole"
Camera1.fx: {c['fx']}
Camera1.fy: {c['fy']}
Camera1.cx: {c['cx']}
Camera1.cy: {c['cy']}
Camera1.k1: {c['k1']}
Camera1.k2: {c['k2']}
Camera1.p1: {c['p1']}
Camera1.p2: {c['p2']}
Camera1.k3: {c['k3']}
Camera.width: {c['width']}
Camera.height: {c['height']}
Camera.fps: {fps}
Camera.RGB: 1
ORBextractor.nFeatures: 800
ORBextractor.scaleFactor: 1.2
ORBextractor.nLevels: 8
ORBextractor.iniThFAST: 20
ORBextractor.minThFAST: 7
''')
    print(f'wrote {out}')


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('calibration', help='ost.yaml from camera_calibration')
    ap.add_argument('--fps', type=int, default=15)
    a = ap.parse_args()
    d, c = load(a.calibration)
    write_camera_info(d)
    update_orb_params(c, a.fps)
    write_orb_settings(c, a.fps)
    print('Done. Rebuild: colcon build --packages-select camera_launch orb_slam3_wrapper')


if __name__ == '__main__':
    main()
